<?php

namespace HideInMatrix\TelegramUpload\Adapters;

use Flarum\Foundation\ValidationException;
use Flarum\Http\UrlGenerator;
use FoF\Upload\Contracts\UploadAdapter;
use FoF\Upload\File;
use HideInMatrix\TelegramUpload\Client\TgDiskClient;
use HideInMatrix\TelegramUpload\Configuration;
use HideInMatrix\TelegramUpload\Exceptions\ApiKeyRejectedException;
use Symfony\Component\HttpFoundation\File\UploadedFile;
use Symfony\Contracts\Translation\TranslatorInterface;

final class Telegram implements UploadAdapter
{
    public string $adapterKey = 'telegram';

    public function __construct(
        private readonly TgDiskClient $client,
        private readonly UrlGenerator $urls,
        private readonly TranslatorInterface $translator
    ) {}

    public function forMime($mime): bool
    {
        return preg_match('~^(image/(jpeg|png|apng|gif|webp|avif|bmp|tiff)|application/(pdf|zip|x-zip-compressed|x-7z-compressed|gzip|x-gzip)|text/plain)$~D', $mime) === 1;
    }

    public function supportsStreams(): bool
    {
        return true;
    }

    public function upload(File $file, ?UploadedFile $upload, $contents)
    {
        $size = is_resource($contents) ? (fstat($contents)['size'] ?? null) : strlen($contents);
        if ($size === null || $size > Configuration::MAX_BYTES) {
            throw new ValidationException(['upload' => $this->translator->trans('hideinmatrix-telegram-upload.api.too_large')]);
        }

        try {
            $id = $this->client->upload($file->uuid, $contents, (int) $size);
        } catch (ApiKeyRejectedException) {
            throw new ValidationException(['upload' => $this->translator->trans('hideinmatrix-telegram-upload.api.authentication_failed')]);
        } catch (\Throwable) {
            // Upstream exceptions may contain sensitive service details.
            throw new ValidationException(['upload' => $this->translator->trans('hideinmatrix-telegram-upload.api.upload_failed')]);
        }

        $file->size = (int) $size;
        $file->remote_id = $id;
        $file->path = 'telegram/'.$id;
        // Keep URLs generated by the original site-local adapter working.
        $file->url = $this->urls->to('api')->route('tinker-telegram.file', ['uuid' => $file->uuid]);

        return $file;
    }

    public function delete(File $file): bool
    {
        // Forum-only deletion: FoF removes the media record; Telegram keeps its copy.
        return true;
    }
}
